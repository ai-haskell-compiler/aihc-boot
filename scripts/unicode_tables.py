#!/usr/bin/env python3
"""Write src/unicode_tables.c: the Unicode character classes of the lexer,
and the general categories of Data.Char.

The C code classifies characters outside ASCII with range tables. This
script makes the tables from Python's unicodedata module. GHC 9.12 uses
Unicode 15.1, which is the version of Python 3.13. Run it again only to
move to a new Unicode version:

    nix shell --inputs-from . nixpkgs#python313 -c \
        python3 scripts/unicode_tables.py > src/unicode_tables.c
"""

import sys
import unicodedata


def ranges(pred):
    out = []
    start = None
    for c in range(0x80, 0x110000):
        ok = pred(chr(c))
        if ok and start is None:
            start = c
        elif not ok and start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def cat(c):
    return unicodedata.category(c)


TABLES = [
    ("uc_alpha", "Letters (L*) and letter numbers (Nl).",
     lambda c: cat(c)[0] == "L" or cat(c) == "Nl"),
    ("uc_numeric", "Numbers (N*).", lambda c: cat(c)[0] == "N"),
    ("uc_upper", "Upper case letters (Lu).", lambda c: cat(c) == "Lu"),
]


# The general categories, in the order of the constructors of
# Data.Char.GeneralCategory.
CATEGORIES = ["Lu", "Ll", "Lt", "Lm", "Lo", "Mn", "Mc", "Me", "Nd", "Nl", "No",
              "Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po", "Sm", "Sc", "Sk", "So",
              "Zs", "Zl", "Zp", "Cc", "Cf", "Cs", "Co", "Cn"]


def category_runs():
    out = []
    for c in range(0, 0x110000):
        k = CATEGORIES.index(cat(chr(c)))
        if out and out[-1][2] == k and out[-1][1] == c - 1:
            out[-1][1] = c
        else:
            out.append([c, c, k])
    return out


def main():
    w = sys.stdout.write
    w("/* Generated by scripts/unicode_tables.py from Unicode %s.\n" % unicodedata.unidata_version)
    w(" * Do not edit. Each table holds sorted, inclusive ranges of code\n")
    w(" * points above 0x7F. */\n\n")
    w("#include \"unicode_tables.h\"\n")
    for name, doc, pred in TABLES:
        rs = ranges(pred)
        w("\n/* %s */\n" % doc)
        w("const unsigned long %s[][2] = {\n" % name)
        for a, b in rs:
            w("    {0x%lX, 0x%lX},\n" % (a, b))
        w("};\n")
        w("const unsigned long %s_len = %d;\n" % (name, len(rs)))
    rs = category_runs()
    w("\n/* The general category of every code point: sorted, inclusive\n")
    w(" * ranges with the index of the category in CATEGORIES. */\n")
    w("const unsigned long uc_category[][3] = {\n")
    for a, b, k in rs:
        w("    {0x%lX, 0x%lX, %d},\n" % (a, b, k))
    w("};\n")
    w("const unsigned long uc_category_len = %d;\n" % len(rs))


main()
